"""Builds the issuer icon pack from Simple Icons (CC0 1.0, https://github.com/simple-icons/simple-icons).

Usage: build_icon_pack.py <extracted simple-icons npm package dir> <android/app dir>

Writes one Android vector drawable per curated slug to src/main/res/drawable/si_<slug>.xml and
the generated Kotlin table src/main/kotlin/.../ui/icons/SimpleIcons.kt, which references every
drawable directly (R.drawable.si_*): resource shrinking and R8 see the references, no lookup by name.
To add an icon: add its slug to SLUGS, run the script, add aliases in IssuerIcons.kt if needed.
"""
